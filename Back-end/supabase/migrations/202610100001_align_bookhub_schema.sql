-- Bookhub application schema additions.
-- Apply to the E-book Supabase project after reviewing the existing policies.
-- Never put database passwords or service-role keys in this file.

alter table public.profiles
  add column if not exists selected_categories text[] not null default '{}',
  add column if not exists selected_formats text[] not null default '{}';

create table if not exists public.user_activity (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  activity_type varchar not null,
  target_type varchar,
  target_id uuid,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists user_activity_user_created_idx
  on public.user_activity (user_id, created_at desc);

alter table public.user_activity enable row level security;

drop policy if exists "Users can read own activity" on public.user_activity;
create policy "Users can read own activity"
  on public.user_activity for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can insert own activity" on public.user_activity;
create policy "Users can insert own activity"
  on public.user_activity for insert
  to authenticated
  with check (auth.uid() = user_id);

-- Keep profile preferences private to their owner.
drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile"
  on public.profiles for select
  to authenticated
  using (auth.uid() = id);

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile"
  on public.profiles for update
  to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- Existing profiles table references auth.users. Create a public profile when
-- Supabase Auth registers a new user; never accept the ID from client input.
create or replace function public.handle_new_bookhub_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, nullif(new.raw_user_meta_data ->> 'full_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_bookhub on auth.users;
create trigger on_auth_user_created_bookhub
  after insert on auth.users
  for each row execute procedure public.handle_new_bookhub_user();
